export const KEYWORD_EMOJI: Record<string, string> = Object.fromEntries(
  KEYWORD_GROUPS.flatMap(([emoji, keys]) => keys.map((key) => [key, emoji])),
);

const REPEATED_LETTER = /^([a-z])\1{2,}$/;
const DIGITS = /^\d+$/;

const WORD_MATCH_MAX = 3;

const WHOLE_WORD = new Set([
  'okay', 'star', 'same', 'this', 'time', 'neru', 'sake', 'ushi', 'atsu', 'heee', 'kuro', 'shiro', 'wash',
  'maru', 'ariga', 'inori', 'pika', 'spec', 'komaru', 'sing', 'kusa', 'naki', 'otsu', 'ohoho', 'rage', 'love',
  'boom', 'nade', 'pen', 'light', 'come', 'hand', 'note', 'hate', 'mata', 'hoko',
]);

function matches(key: string, words: string[], joined: string): boolean {
  if (key.length <= WORD_MATCH_MAX || WHOLE_WORD.has(key)) return words.includes(key);
  return joined.includes(key);
}

export function suggestEmoji(talent: string, rawName: string): string {
  const slug = toSlackName(talent, rawName);
  const words = slug.split('-');
  const rest = words.length > 1 ? words.slice(1) : words;
  const unnumbered = rest.map((w) => (DIGITS.test(w) ? w : w.replace(/\d+$/, '')));
  const candidates = [...rest, ...unnumbered];
  const joined = candidates.join('-');
  const last = rest[rest.length - 1];
  if (rest.includes('no') && last !== 'no' && last.length <= WORD_MATCH_MAX) return '🔤';
  for (const [emoji, keys] of KEYWORD_GROUPS) {
    for (const key of keys) {
      if (matches(key, candidates, joined)) return emoji;
    }
  }
  if (unnumbered.every((w) => REPEATED_LETTER.test(w))) return '🔤';
  if (rest.every((w) => DIGITS.test(w))) return '🔢';
  if (rest.length === 1 && rest[0].length <= 2) return '🔤';
  if (last.length === 1) return '🔤';
  for (const w of candidates) {
    if (w in ALIAS_EMOJI) return ALIAS_EMOJI[w];
  }
  return TALENT_EMOJI[talent] ?? FALLBACK_EMOJI;
}

export function isSingleEmoji(value: string): boolean {
  const trimmed = value.trim();
  if (!trimmed) return false;
  const graphemes = [...new Intl.Segmenter(undefined, { granularity: 'grapheme' }).segment(trimmed)];
  if (graphemes.length !== 1) return false;
  return /\p{Extended_Pictographic}|\p{Regional_Indicator}/u.test(trimmed);
}
